import { neon } from '@neondatabase/serverless';

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is required');
}

const sql = neon(process.env.DATABASE_URL);

await sql.transaction([
  sql.query(`
    CREATE TABLE IF NOT EXISTS password_reset_tokens (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      token_hash text NOT NULL UNIQUE,
      user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at timestamptz NOT NULL,
      used_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now(),
      CONSTRAINT password_reset_token_hash_length
        CHECK (char_length(token_hash) = 64)
    )
  `),
  sql.query(`
    CREATE INDEX IF NOT EXISTS password_reset_tokens_user_recent_idx
    ON password_reset_tokens (user_id, created_at DESC)
  `),
  sql.query(`
    CREATE INDEX IF NOT EXISTS password_reset_tokens_active_idx
    ON password_reset_tokens (expires_at)
    WHERE used_at IS NULL
  `)
], { isolationLevel: 'Serializable' });

const [validation] = await sql.query(`
  SELECT
    to_regclass('public.password_reset_tokens') IS NOT NULL AS table_exists,
    EXISTS (
      SELECT 1
      FROM pg_constraint
      WHERE conname = 'password_reset_token_hash_length'
    ) AS token_hash_limit,
    EXISTS (
      SELECT 1
      FROM pg_indexes
      WHERE indexname = 'password_reset_tokens_user_recent_idx'
    ) AS recent_index
`);

if (
  !validation?.table_exists ||
  !validation?.token_hash_limit ||
  !validation?.recent_index
) {
  throw new Error(`Password reset schema validation failed: ${JSON.stringify(validation)}`);
}

console.log('Password reset schema applied and validated.');
