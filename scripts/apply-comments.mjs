import { neon } from '@neondatabase/serverless';

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is required');
}

const sql = neon(process.env.DATABASE_URL);

await sql.transaction([
  sql.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS ranking_options_ranking_id_id_unique
    ON ranking_options (ranking_id, id)
  `),
  sql.query(`
    CREATE TABLE IF NOT EXISTS ranking_comments (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ranking_id text NOT NULL REFERENCES rankings(id) ON DELETE CASCADE,
      user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      option_id bigint NOT NULL,
      body text NOT NULL,
      status text NOT NULL DEFAULT 'published',
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now(),
      CONSTRAINT ranking_comments_one_per_user UNIQUE (ranking_id, user_id),
      CONSTRAINT ranking_comments_option_fkey
        FOREIGN KEY (ranking_id, option_id)
        REFERENCES ranking_options(ranking_id, id)
        ON DELETE CASCADE,
      CONSTRAINT ranking_comments_body_length
        CHECK (char_length(btrim(body)) BETWEEN 1 AND 200),
      CONSTRAINT ranking_comments_status
        CHECK (status IN ('published', 'hidden'))
    )
  `),
  sql.query(`
    CREATE INDEX IF NOT EXISTS ranking_comments_recent_idx
    ON ranking_comments (ranking_id, created_at DESC, id DESC)
    WHERE status = 'published'
  `)
], { isolationLevel: 'Serializable' });

const [validation] = await sql.query(`
  SELECT
    to_regclass('public.ranking_comments') IS NOT NULL AS table_exists,
    EXISTS (
      SELECT 1
      FROM pg_constraint
      WHERE conname = 'ranking_comments_one_per_user'
    ) AS one_per_user,
    EXISTS (
      SELECT 1
      FROM pg_constraint
      WHERE conname = 'ranking_comments_body_length'
    ) AS body_limit
`);

if (
  !validation?.table_exists ||
  !validation?.one_per_user ||
  !validation?.body_limit
) {
  throw new Error(`Comment schema validation failed: ${JSON.stringify(validation)}`);
}

console.log('Comment schema applied and validated.');
